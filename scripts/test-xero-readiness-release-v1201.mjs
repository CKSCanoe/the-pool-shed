import fs from 'node:fs';import assert from 'node:assert/strict';
const pkg=JSON.parse(fs.readFileSync('package.json','utf8'));
const [major,minor]=pkg.version.split('.').map(Number);
assert(major>1||(major===1&&minor>=20),'Xero-ready regression guard requires release 1.20.1 or newer');
const sw=fs.readFileSync('public/service-worker.js','utf8');
const html=fs.readFileSync('public/index.html','utf8');
assert(sw.includes(`pool-shed-v${pkg.version}-`),'Service-worker cache must use the current release while retaining Xero-ready controls');
assert(html.includes(`v=${pkg.version}`),'Runtime asset cache versions must use the current release');
assert(fs.existsSync('XERO-CONNECTION-READY.md'),'Release must include the deferred live-connection checklist');
const accounting=fs.readFileSync('server/accounting.js','utf8');
assert(accounting.includes("XERO_INTEGRATION_MODE||'ready'"),'Xero must default to Ready mode');
assert(accounting.includes('if(!state.liveEnabled)'),'Xero provider operations must stay locked outside Live mode');
console.log(`PASS Xero connection-ready controls retained on v${pkg.version}`);
