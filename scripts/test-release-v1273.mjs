import fs from 'node:fs';
import assert from 'node:assert/strict';
const pkg=JSON.parse(fs.readFileSync('package.json','utf8'));
const release=pkg.version;
const [major,minor,patch]=release.split('.').map(Number);
const index=fs.readFileSync('public/index.html','utf8');
const sw=fs.readFileSync('public/service-worker.js','utf8');
const legacy=fs.readFileSync('public/assets/js/01-legacy-01.js','utf8');
const readiness=fs.readFileSync('public/production-readiness-engine.js','utf8');
const build=fs.readFileSync('scripts/build.sh','utf8');
assert(major>1||(major===1&&(minor>27||(minor===27&&patch>=3))),'Azzy v1.27.3 authority requires v1.27.3 or newer');
assert.match(index,new RegExp('app\\.css\\?v='+release.replace(/\./g,'\\.')));
assert.match(sw,new RegExp('pool-shed-v'+release.replace(/\./g,'\\.')+'-'));
assert.match(legacy,new RegExp('Pool Shed v'+release.replace(/\./g,'\\.')+' · Pool Bros Ltd'));
assert.match(legacy,new RegExp('service-worker\\.js\\?v='+release.replace(/\./g,'\\.')));
assert.match(readiness,new RegExp("VERSION='"+release.replace(/\./g,'\\.')+"'"));
assert.match(pkg.scripts['test:deployment']||'',/test-azzy-panel-v1273\.mjs/);
assert.match(pkg.scripts['test:deployment']||'',/test-release-v1273\.mjs/);
assert.match(build,/test-azzy-panel-v1273\.mjs/);
assert.match(build,/test-release-v1273\.mjs/);
console.log(`PASS v1.27.3 Azzy panel/cache authority retained on v${release}`);
