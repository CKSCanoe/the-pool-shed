import fs from 'node:fs';
import assert from 'node:assert/strict';
const html=fs.readFileSync('public/index.html','utf8');
assert.ok(fs.existsSync('public/notifications-command-workspace.js'),'Notifications workspace missing');
const js=fs.readFileSync('public/notifications-command-workspace.js','utf8');
assert.ok(html.includes('id="notificationButton"'),'bell button missing');
assert.ok(html.includes('class="notification-icon"')&&html.includes('<svg'),'bell should use a controlled vector icon');
assert.ok(!html.includes('>🔔<'),'platform emoji bell must not be the production icon');
assert.ok(html.includes('aria-label="Notifications"'),'bell needs accessible name');
assert.ok(html.includes('aria-expanded="false"'),'bell needs collapsed state');
assert.ok(html.includes('aria-controls="notificationsCommandRoot"'),'bell needs drawer relationship');
assert.ok(html.includes('id="notificationsCommandRoot"'),'drawer root missing');
assert.ok(html.indexOf('notifications-command-engine.js')<html.indexOf('notifications-command-workspace.js'),'engine must load before workspace');
for(const token of ['PoolShedNotificationsCommand','notifications-command-drawer','Mark all as read','data-nc-filter','data-nc-action="open"','data-nc-action="read"','data-nc-action="archive"','Notification history']) assert.ok(js.includes(token),`workspace missing ${token}`);
assert.ok(/Escape/.test(js),'Escape close handling missing');
assert.ok(js.includes('event.shiftKey')&&/Tab/.test(js),'focus trap must use the real shiftKey state');
assert.ok(!js.includes('event.Shift'),'focus trap must not use a non-existent event.Shift property');
assert.ok(/aria-modal/.test(js),'drawer modal semantics missing');
assert.ok(/restoreFocus|lastFocused/.test(js),'trigger focus restoration missing');
assert.ok(!/Missing Stock/.test(js),'Notifications workspace must not route to legacy Missing Stock shortcut');
console.log('PASS Notifications Command workspace structure, accessibility and interactions');
