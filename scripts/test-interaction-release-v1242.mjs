import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
const root=path.resolve(path.dirname(new URL(import.meta.url).pathname),'..');
const read=(p)=>fs.readFileSync(path.join(root,p),'utf8');
const pkg=JSON.parse(read('package.json'));
const release=pkg.version;
const index=read('public/index.html');
const sw=read('public/service-worker.js');
const legacy=read('public/assets/js/01-legacy-01.js');
const readiness=read('public/production-readiness-engine.js');
const current=read('CURRENT-RELEASE.txt');
const parts=release.split('.').map(Number);
assert.ok(parts[0]>1||(parts[0]===1&&(parts[1]>24||(parts[1]===24&&(parts[2]||0)>=2))),'interaction/navigation guard requires v1.24.2 or newer');
assert.match(index,new RegExp(`app\\.css\\?v=${release.replace(/\./g,'\\.')}`),'index must cache-bust CSS at current release');
assert.match(sw,new RegExp(`pool-shed-v${release.replace(/\./g,'\\.')}-`),'service-worker cache must use current release');
assert.match(legacy,new RegExp(`Pool Shed v${release.replace(/\./g,'\\.')} · Pool Bros Ltd`),'login footer must show current release');
assert.match(legacy,new RegExp(`service-worker\\.js\\?v=${release.replace(/\./g,'\\.')}`),'service-worker registration must use current release');
assert.ok(readiness.includes(`const VERSION='${release}'`),'production readiness must report current release');
assert.ok(current.includes(`v${release}`),'current release note must identify package version');
console.log(`PASS v1.24.2 interaction/navigation contract retained on v${release}`);
