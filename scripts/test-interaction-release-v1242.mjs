import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
const root=path.resolve(path.dirname(new URL(import.meta.url).pathname),'..');
const read=(p)=>fs.readFileSync(path.join(root,p),'utf8');
const pkg=JSON.parse(read('package.json'));
const index=read('public/index.html');
const sw=read('public/service-worker.js');
const legacy=read('public/assets/js/01-legacy-01.js');
const readiness=read('public/production-readiness-engine.js');
const current=read('CURRENT-RELEASE.txt');
assert.equal(pkg.version,'1.24.2','package version must be 1.24.2');
assert.match(index,/app\.css\?v=1\.24\.2/,'index must bust CSS cache at 1.24.2');
assert.doesNotMatch(index,/\?v=1\.24\.1/,'index must not retain 1.24.1 asset cache refs');
assert.match(sw,/pool-shed-v1\.24\.2-/,'service-worker cache must be unique to 1.24.2');
assert.doesNotMatch(sw,/\?v=1\.24\.1/,'service worker must not precache 1.24.1 assets');
assert.match(legacy,/Pool Shed v1\.24\.2 · Pool Bros Ltd/,'login footer must show 1.24.2');
assert.match(legacy,/service-worker\.js\?v=1\.24\.2/,'service-worker registration must be cache-busted');
assert.match(readiness,/const VERSION='1\.24\.2'/,'production readiness must report 1.24.2');
assert.match(current,/Pool Shed v1\.24\.2 — Interaction & Navigation Authority/,'current release must identify v1.24.2');
console.log('PASS v1.24.2 release/cache wiring');
