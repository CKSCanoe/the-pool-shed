import fs from 'node:fs';
import assert from 'node:assert/strict';
const html=fs.readFileSync('public/proposal.html','utf8');
const js=fs.readFileSync('public/quote-customer-portal.js','utf8');
const api=fs.readFileSync('api/quote.js','utf8');
const sql=fs.readFileSync('database/007-quote-studio.sql','utf8');
const vercel=JSON.parse(fs.readFileSync('vercel.json','utf8'));
assert.match(html,/noindex,nofollow,noarchive/);
assert.match(html,/quote-customer-portal\.js\?v=1\.29\.0/);
for(const internal of ['01-legacy-01.js','quote-studio-engine.js','quote-studio-workspace.js','project-workspace.js','purchase-workspace.js'])assert(!html.includes(internal),'customer portal must not load '+internal);
for(const forbidden of ['unitCost','supplierSnapshot','commercialSnapshot','purchaseOrders','costSnapshot','financeDocumentId'])assert(!js.includes(forbidden),'customer JavaScript must not contain internal field '+forbidden);
assert.match(api,/public_payload/);assert.match(api,/commercial_payload/);assert.match(api,/token_hash/);assert.match(api,/tokenHash\(plain\)/);
assert.match(api,/select=id,quote_id,version_number,status,expires_at,accepted_at/,'staff feed must avoid returning proposal commercial payload');
assert.match(sql,/revoke all on public\.ps_quote_publications,public\.ps_quote_events,public\.ps_quote_messages,public\.ps_quote_acceptances from anon,authenticated/);
assert.match(sql,/grant all on public\.ps_quote_publications,public\.ps_quote_events,public\.ps_quote_messages,public\.ps_quote_acceptances to service_role/);
assert.match(sql,/Published quote versions are immutable/);
assert.match(sql,/Accepted quote evidence is immutable/);
const rewrite=(vercel.rewrites||[]).find(x=>String(x.source).includes('api'));
assert(rewrite,'SPA rewrite must continue to exclude API/static files');
assert.equal((js.match(/track\('open'/g)||[]).length,0,'public GET is the single source of first-open tracking');
assert.equal((js.match(/track\('option_change'/g)||[]).length,0,'choice endpoint is the single source of option-change tracking');
assert.equal((js.match(/track\('question'/g)||[]).length,0,'question endpoint is the single source of question tracking');
assert.equal((js.match(/track\('accepted'/g)||[]).length,0,'accept endpoint is the single source of accepted tracking');
assert.match(js,/track\('acceptance'/,'acceptance-start signal should remain separate from accepted event');
console.log('PASS v1.29.0 customer portal isolation, service-role quote tables, immutable acceptance and non-duplicated engagement events');
